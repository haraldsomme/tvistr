// The decisions the letter can cite, read for what the committee decided and what it relied on (docs/henvisninger.md, scripts/sjekk-henvisninger.ts). The letter cites the one where the buyer stands at least as strong on that (velgHenvisning).

export const GRUPPER = ["motor", "elektrisk", "understell", "km_service", "rust", "bremser", "girkasse", "fukt", "klimaanlegg", "skade", "batteri"] as const;
export type Gruppe = (typeof GRUPPER)[number];

// The rule the letter's paragraph on the defect rests on: the § 18 presumption, a report that the
// defect was there at delivery, wrong information from the dealer (§ 16), or that the car was worse
// than the buyer had reason to expect (§ 15).
export const REGELGRUNNLAG = ["formodning", "rapport", "opplysning", "forventning"] as const;
export type Regelgrunnlag = (typeof REGELGRUNNLAG)[number];

export type Organ = "Forbrukerklageutvalget" | "Forbrukertvistutvalget";

// What the committee took a position on: a car worse than the buyer could expect (§ 15, § 16 first
// paragraph a), wrong or withheld information (§ 16 b/c), or a defect that was there at delivery (§ 18,
// an expert statement or other evidence).
export const SPORSMAL = ["forventning", "opplysning", "levering"] as const;
export type Sporsmal = (typeof SPORSMAL)[number];

// What the buyer in the decision had been told or accepted, weakest buyer position last.
export const OPPLYST = ["ingenting", "som_den_er", "feilen_opplyst"] as const;
export type Opplyst = (typeof OPPLYST)[number];

export type Henvisning = {
  vedtakId: number;
  // As the committee cites its own decisions: FKU-2023-13923 for case 23/13923.
  ref: string;
  organ: Organ;
  // The day of the decision (ÅÅÅÅ-MM-DD), as in «Porsgrunn, den …».
  dato: string;
  kildeUrl: string;
  // By the cited purchase date: the 2024 changes apply to contracts made from 1 January 2024.
  lov: "før_2024" | "etter_2024";
  // The cited buyer had the § 18 presumption (six months before 2024, two years from 2024).
  presumsjon: boolean;
  // What the committee took a position on; at least one.
  sporsmal: Sporsmal[];
  // The factors (ids in MOMENTER) the committee put decisive weight on.
  vekt: string[];
  // «Utvalget la vekt på at …», one or two sentences, without names, make and model.
  begrunnelse: string;
  // The cited car's age at purchase in whole years, its mileage and its price, as the decision gives them.
  alder: number;
  km: number | null;
  pris: number;
  opplyst: Opplyst;
  // When the defect showed in the cited case, by the decision text.
  botte: Reklamasjonsbotte;
  tid: string;
  gruppe: Gruppe;
  // Short, without make and model: «rust i dører, panser og tak».
  feil: string;
  // «prisavslag satt lik utbedringskostnadene».
  utfall: string;
};

export type Faktum = "alder" | "km" | "pris" | "opplyst" | "tid";
// What the letter knows about the buyer beyond Faktorer: the moments asked in this case (sporbare), those
// with a favourable answer (dekket), and what they were told before buying.
export type Kjoper = { sporbare: ReadonlySet<string>; dekket: ReadonlySet<string>; opplyst: Opplyst };
export type ValgtHenvisning = {
  henvisning: Henvisning;
  // The buyer's question is the one the decision decided; false for the fallback.
  sammeSporsmal: boolean;
  // Shared with the buyer, main question first.
  sporsmal: Sporsmal[];
  // In vekt, asked, favourable answer.
  dekket: string[];
  // In vekt, asked, no favourable answer.
  mangler: string[];
  // In vekt, not asked in this case.
  ukjent: string[];
  sterkere: Faktum[];
  likt: Faktum[];
  svakere: Faktum[];
  annenFeil: boolean;
};

